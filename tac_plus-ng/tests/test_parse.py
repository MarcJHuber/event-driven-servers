"""tac_plus-ng -P: configuration syntax check, no network.

Every sample shipped in tac_plus-ng/sample and tac_plus-ng/extra must
parse, except those in SAMPLE_EXCLUDED: they need files of an installed
system (certificates, MAVIS scripts, PAM helper) at parse time, or they
run into a parser bug. The list is checked both ways: an excluded sample
that starts to parse, or fails with another message, fails the test too,
so the list doesn't rot.
"""

import glob
import os
import tempfile
import unittest

from tactest import config, features
from tactest.daemon import parse_only

TESTS = os.path.dirname(os.path.abspath(__file__))
COMPONENT = os.path.dirname(TESTS)
TOP = os.path.dirname(COMPONENT)
CONFIGS = os.path.join(TESTS, "configs")

# name: (why it fails, text its error output must contain -- or one of several texts --
#        or None if it prints none)
SAMPLE_EXCLUDED = {
    "sample/radius-dict.cfg": (
        "a fragment for \"include\", not a configuration of its own",
        "but got 'radius.dictionary'"),
    "sample/tac_plus-ng.cfg": (
        "needs /usr/local/sbin/pammavis (PAM only); before that, on musl, \"dns preload file\" fails on "
        "$CONFDIR/hosts.txt: glob() sees the name before $CONFDIR is expanded (glibc passes it on)",
        ("/usr/local/sbin/pammavis: No such file", "glob($CONFDIR/hosts.txt)")),
    "sample/tac_plus-ng-demo-pam.cfg": (
        "needs /usr/local/sbin/pammavis (built only with PAM)",
        "/usr/local/sbin/pammavis: No such file"),
    "sample/tac_plus-ng-multivendor.cfg": (
        "needs /usr/local/sbin/pammavis (built only with PAM)",
        "/usr/local/sbin/pammavis: No such file"),
    "sample/tac_plus-ng-tls.cfg": (
        "the democa certificates are generated by sample/democa/Makefile; fails without a message",
        None),
    "sample/tac_plus-ng-radsec.cfg": (
        "the democa certificates are generated by sample/democa/Makefile; fails without a message",
        None),
    "sample/tls-fingerprint-demo/tac_plus-ng-fingerprint.cfg": (
        "includes client.selfsigned.fingerprint, which tls-fingerprint-demo/mkcert.sh generates",
        "client.selfsigned.fingerprint"),
    "extra/tac_plus-ng.cfg-ads": (
        "runs /usr/local/lib/mavis/mavis_tacplus-ng_ldap.pl",
        "/usr/local/lib/mavis/mavis_tacplus-ng_ldap.pl: No such file"),
    "extra/tac_plus-ng.cfg-shadow": (
        "runs /usr/local/lib/mavis/mavis_tacplus_shadow.pl",
        "/usr/local/lib/mavis/mavis_tacplus_shadow.pl: No such file"),
}

# without OpenSSL ("configure --minimum") these stop earlier: "tls" is no keyword then
NEEDS_OPENSSL = ("sample/tac_plus-ng-tls.cfg", "sample/tac_plus-ng-radsec.cfg",
                 "sample/tls-fingerprint-demo/tac_plus-ng-fingerprint.cfg")
WITHOUT_OPENSSL = "but got 'tls'"

SANITIZER_TEXT = ("Sanitizer", "runtime error")


def samples():
    found = glob.glob(os.path.join(COMPONENT, "sample", "*.cfg"))
    found += glob.glob(os.path.join(COMPONENT, "sample", "*", "*.cfg"))
    found += glob.glob(os.path.join(COMPONENT, "extra", "tac_plus-ng.cfg-*"))
    return sorted(os.path.relpath(p, COMPONENT) for p in found)


def check(path):
    # from the top of the tree: some samples name scripts relative to it
    return parse_only(path, cwd=TOP)


def sanitizer_findings(out):
    return [line for line in out.splitlines() if any(t in line for t in SANITIZER_TEXT)]


class Samples(unittest.TestCase):
    def test_samples_parse(self):
        for name in samples():
            if name in SAMPLE_EXCLUDED:
                continue
            with self.subTest(sample=name):
                code, out = check(os.path.join(COMPONENT, name))
                self.assertEqual(code, 0, out)
                self.assertEqual(sanitizer_findings(out), [], out)

    def test_excluded_samples_still_fail(self):
        """Each excluded sample fails for its stated reason: an exit code, not a crash, and its message."""
        for name, (reason, expected) in sorted(SAMPLE_EXCLUDED.items()):
            with self.subTest(sample=name):
                path = os.path.join(COMPONENT, name)
                self.assertTrue(os.path.exists(path), "%s is gone: drop it from SAMPLE_EXCLUDED" % name)
                code, out = check(path)
                self.assertNotEqual(code, 0, "%s parses now: drop it from SAMPLE_EXCLUDED (%s)" % (name, reason))
                self.assertGreater(code, 0, "%s: killed by signal %d, not a parse error\n%s" % (name, -code, out))
                self.assertEqual(sanitizer_findings(out), [], out)
                if name in NEEDS_OPENSSL and "openssl" not in features():
                    reason, expected = "built without OpenSSL", WITHOUT_OPENSSL
                if expected is None:
                    self.assertEqual(out.strip(), "", "%s prints a message now: put it into SAMPLE_EXCLUDED" % name)
                else:
                    texts = expected if isinstance(expected, tuple) else (expected,)
                    self.assertTrue(any(t in out for t in texts),
                                    "%s fails for another reason than: %s\n%s" % (name, reason, out))


class OwnConfigs(unittest.TestCase):
    def test_good_configs_parse(self):
        good = sorted(glob.glob(os.path.join(CONFIGS, "good-*.cfg")))
        self.assertTrue(good)
        for path in good:
            with self.subTest(config=os.path.basename(path)):
                code, out = check(path)
                self.assertEqual(code, 0, out)

    def test_bad_configs_are_rejected(self):
        bad = sorted(glob.glob(os.path.join(CONFIGS, "bad-*.cfg")))
        self.assertTrue(bad)
        for path in bad:
            with self.subTest(config=os.path.basename(path)):
                code, out = check(path)
                self.assertGreater(code, 0, out)
                self.assertEqual(sanitizer_findings(out), [], out)
                self.assertIn(os.path.basename(path), out, "the error doesn't name the file")

    def test_harness_base_config_parses(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "base.cfg")
            with open(path, "w") as f:
                f.write(config.render(tmp=tmp, port=4949))
            code, out = check(path)
            self.assertEqual(code, 0, out)


if __name__ == "__main__":
    unittest.main()
