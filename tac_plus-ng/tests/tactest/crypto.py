def _permute(value, table, width):
    out = 0
    for pos in table:
        out = (out << 1) | ((value >> (width - pos)) & 1)
    return out


def des_encrypt(key, block):
    """One block, ECB; key is 8 bytes (parity bits ignored)."""
    k = _permute(int.from_bytes(key, "big"), _PC1, 64)
    c, d = k >> 28, k & 0x0FFFFFFF
    subkeys = []
    for s in _SHIFTS:
        c = ((c << s) | (c >> (28 - s))) & 0x0FFFFFFF
        d = ((d << s) | (d >> (28 - s))) & 0x0FFFFFFF
        subkeys.append(_permute((c << 28) | d, _PC2, 56))
    v = _permute(int.from_bytes(block, "big"), _IP, 64)
    left, right = v >> 32, v & 0xFFFFFFFF
    for sk in subkeys:
        x = _permute(right, _E, 32) ^ sk
        out = 0
        for i in range(8):
            six = (x >> (42 - 6 * i)) & 0x3F
            row, col = ((six & 0x20) >> 4) | (six & 1), (six >> 1) & 0xF
            out = (out << 4) | _S[i][row * 16 + col]
        left, right = right, left ^ _permute(out, _P, 32)
    return _permute((right << 32) | left, _FP, 64).to_bytes(8, "big")


def _des_key(seven):
    """56 key bits in 7 bytes -> 8 DES key bytes (RFC 2433 section A.6, parity bits zero)."""
    n = int.from_bytes(seven, "big")
    return bytes(((n >> (49 - 7 * i)) & 0x7F) << 1 for i in range(8))


def nt_hash(password):
    return md4(password.encode("utf-16-le"))


def challenge_response(challenge, password_hash):
    """RFC 2433 ChallengeResponse(): three DES blocks over the zero-padded hash."""
    z = password_hash + b"\x00" * (21 - len(password_hash))
    return b"".join(des_encrypt(_des_key(z[i:i + 7]), challenge) for i in (0, 7, 14))


def mschapv2_challenge_hash(peer_challenge, authenticator_challenge, username):
    """RFC 2759 ChallengeHash()."""
    return hashlib.sha1(peer_challenge + authenticator_challenge + username).digest()[:8]
