"""MD4 and DES in pure Python, for MS-CHAP (RFC 2433, RFC 2759).

hashlib offers MD4 only where OpenSSL still has its legacy provider, and
the standard library has no DES at all. Both are needed for the NT
response only, so speed doesn't matter.
"""

import hashlib
import struct


def _rol(x, n):
    x &= 0xFFFFFFFF
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF


def md4(data):
    """RFC 1320."""
    msg = bytes(data) + b"\x80"
    msg += b"\x00" * ((56 - len(msg) % 64) % 64) + struct.pack("<Q", len(data) * 8)
    a, b, c, d = 0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476
    for off in range(0, len(msg), 64):
        x = struct.unpack("<16I", msg[off:off + 64])
        aa, bb, cc, dd = a, b, c, d

        def f(x_, y, z):
            return (x_ & y) | (~x_ & z)

        def g(x_, y, z):
            return (x_ & y) | (x_ & z) | (y & z)

        def h(x_, y, z):
            return x_ ^ y ^ z
        for i in range(16):
            k, s = i, (3, 7, 11, 19)[i % 4]
            a, b, c, d = d, _rol(a + f(b, c, d) + x[k], s), b, c
        for i in range(16):
            k, s = (i % 4) * 4 + i // 4, (3, 5, 9, 13)[i % 4]
            a, b, c, d = d, _rol(a + g(b, c, d) + x[k] + 0x5A827999, s), b, c
        for i in range(16):
            k, s = (0, 8, 4, 12, 2, 10, 6, 14, 1, 9, 5, 13, 3, 11, 7, 15)[i], (3, 9, 11, 15)[i % 4]
            a, b, c, d = d, _rol(a + h(b, c, d) + x[k] + 0x6ED9EBA1, s), b, c
        a, b, c, d = [(v + w) & 0xFFFFFFFF for v, w in ((a, aa), (b, bb), (c, cc), (d, dd))]
    return struct.pack("<4I", a, b, c, d)


